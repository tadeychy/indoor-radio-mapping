def Draw(matrix,CSV,setup,ap,enco):
    if setup<=20:
        index_search = setup - 1
    else:
        index_search = setup - 21
    matrix_ind = np.array(matrix, dtype=np.float64)
    matrix = [row[:] for row in matrix]
    df = pd.read_csv(CSV, encoding=enco)
    x = df["Strength"].tolist()
    cleaned_x = [int(i.replace("dBm", "")) for i in x]
    for i in range(0,27):
        for col in range(0,30):
            if matrix[i][col] != 0:
                matrix[i][col] = cleaned_x[(matrix[i][col]-1)+(26*(index_search))]
    data_group = np.array(matrix, dtype=np.float64)
    IJS.rssi_contour_plot(data_group, matrix_ind, ap, setup_num=setup, save_figure=True)


