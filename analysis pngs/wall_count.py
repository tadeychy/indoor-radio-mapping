# 2. Setup Parameters & Geometry
mesh = o3d.io.read_triangle_mesh("ply/mesh/final_mesh_rotated_cut.ply")
grid_spacing = 0.225
x_offset = 4.0
y_offset = 3.5
z_offset = -1

matrix_ind_np = np.array(matrix, dtype=np.float64)

# 3. Extract points from matrix indices
y_indices, x_indices = np.nonzero(matrix_ind_np)
points_meas = np.column_stack((
    -y_indices * grid_spacing + x_offset,
    -x_indices * grid_spacing + y_offset,
    np.full(len(x_indices), 1.5 + z_offset)
))
for i in range(0, 30):
    # 4. Compute Wall Counts
    wall_counts = IJS.estimate_wall_count(mesh, points_meas[i], points_meas, max_walls=3)

    # 5. Print Results
    print(f"\nWall counts for AP at point {i}:")
    for idx, (pt, wc) in enumerate(zip(points_meas, wall_counts)):
        print(f"  Point {idx:3d} ({pt[0]:8.2f}, {pt[1]:8.2f}, {pt[2]:8.2f}): {wc} wall(s)")

    # 6. Reconstruct grid and map wall values directly
    wall_grid = np.full(matrix_ind_np.shape, np.nan)
    wall_grid[y_indices, x_indices] = wall_counts

    # 7. Visualization
    plt.figure(figsize=(8, 8))
    plt.title(f"Estimated walls from AP {i + 1}")
    im = plt.imshow(wall_grid, cmap="plasma", interpolation="nearest")
    plt.colorbar(im, label="Number of walls")

    # Mark AP position
    ap_r, ap_c = y_indices[i], x_indices[i]
    plt.scatter(ap_c, ap_r, c="lime", s=200, marker="*", label=f"AP {i + 1}", zorder=5)

    plt.legend()
    plt.tight_layout()

    plt.savefig(f"wall_count_{i + 1}.png", dpi=300, bbox_inches="tight", transparent=True)
    plt.show()
    plt.close()
